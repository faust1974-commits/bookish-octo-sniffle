function findStatuteAnswer(q) {
  const entries = Object.values(F.indexes.citations);
  const cleaned = q.replace(/[,]/g, ' ').trim();
  const match = entries.filter((e) => {
    const v = e.value.toLowerCase();
    const bare = v.replace(/,?\s*(f\.s\.|f\.a\.c\.)$/, '');
    return cleaned.includes(bare) || v.includes(cleaned) || (cleaned.length > 3 && bare.includes(cleaned));
  });
  if (!match.length) return null;
  match.sort((a, b) => b.benchmarks.length - a.benchmarks.length);
  const top = match.slice(0, 6);
  return {
    title: `Legal references matching "${q}"`,
    html: top.map((e) => `<div class="stack" style="margin-bottom:8px">
      <div><span class="tag cite">${esc(e.value)}</span> <span class="muted small">${e.kind} - ${plural(e.benchmarks.length, 'benchmark')}</span></div>
      <ul class="small" style="margin:2px 0 0">${e.benchmarks.map((uid) => {
        const b = BY_UID.get(uid);
        return `<li><a href="#/b/${uid}"><code>${b.id}</code></a> ${esc(b.text.slice(0, 120))}${b.text.length > 120 ? '...' : ''} <span class="muted">- ${esc(b._course.title)}</span></li>`;
      }).join('')}</ul></div>`).join(''),
  };
}

