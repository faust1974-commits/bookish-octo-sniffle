function lessonMarkdown() {
  const items = state.selection.map((uid) => BY_UID.get(uid));
  if (!items.length) return '';
  const L = state.lesson;
  const coursesUsed = [...new Set(items.map((b) => b._course))];
  const stdsUsed = [...new Set(items.map((b) => b._std))];
  const perf = items.filter((b) => b.modality === 'performance');
  const know = items.filter((b) => b.modality === 'knowledge');
  const topicIds = [...new Set(items.flatMap((b) => b.topics))];
  const cites = [...new Set(items.flatMap((b) => [...b.citations.statutes, ...b.citations.rules, ...b.citations.federal]))];
  const cases = [...new Set(items.flatMap((b) => b.citations.cases))];
  const named = [...new Set(items.flatMap((b) => b.citations.named))];
  const periods = Math.round(items.reduce((a, b) => a + b.suggestedPeriods, 0) * 10) / 10;
  const support = topicIds.map((t) => TOPIC_SUPPORT[t]).filter(Boolean);
  const materials = [...new Set(support.flatMap((s) => s.materials))];
  const activities = [...new Set(support.flatMap((s) => s.activities))];
  const topicLabels = topicIds.map((t) => TOPIC_LABEL.get(t));

  const out = [];
  out.push(`# ${L.title || `${topicLabels[0] || 'Criminal Justice Operations'} - lesson plan`}`, '');
  out.push(`**Program:** ${P.programTitle} (${P.programNumber}) | **CIP:** ${P.cipNumber} | **Cluster:** ${P.careerCluster}`);
  out.push(`**Course(s):** ${coursesUsed.map((c) => `${c.title} (${c.courseNumber})`).join('; ')}`);
  out.push(`**Date:** ${L.date || '______'} | **Length:** ${L.periods || '______'}`);
  const pacingBasis = coursesUsed.find((c) => c.periodsPerCourse) || SEQUENCED[0];
  out.push('', `*Framework pacing allocation for these ${plural(items.length, 'benchmark')}: about ${periods} instructional period(s) of the ${pacingBasis.periodsPerCourse} in a ${pacingBasis.credit}-credit course. That is a share of the course's time, not the length of one class - split it across as many lessons as the work needs.*`, '');

  out.push('## Standards and benchmarks addressed', '');
  stdsUsed.forEach((s) => {
    out.push(`**${s.id} ${s.text}**`);
    items.filter((b) => b._std === s).forEach((b) => {
      out.push(`- ${b.id} ${b.text}${b.optional ? ' *(optional in framework)*' : ''}`);
      b.bullets.forEach((x) => out.push(`  ${'  '.repeat(x.depth)}- ${x.text}`));
    });
    out.push('');
  });

  out.push('## Learning objectives', '', 'Students will be able to:', '');
  items.forEach((b) => out.push(`- ${titleCase(lowerFirst(b.text.replace(/\s*\(optional\)\s*/i, '')))} *(${b.id}, ${b.cognitiveLabel})*`));
  out.push('');

  out.push('## Essential questions', '');
  stdsUsed.slice(0, 2).forEach((s) => {
    out.push(`- What does "${s.text.replace(/\.$/, '')}" require of a criminal justice professional on the job?`);
  });
  if (topicLabels.length) out.push(`- Where do ${topicLabels.slice(0, 2).join(' and ').toLowerCase()} decisions go wrong, and what prevents it?`);
  out.push('');

  if (cites.length || cases.length || named.length) {
    out.push('## Legal authority and key references', '');
    cites.forEach((c) => out.push(`- ${c}`));
    cases.forEach((c) => out.push(`- Case law: ${c}`));
    named.forEach((c) => out.push(`- ${c}`));
    out.push('');
  }

  out.push('## Materials and equipment', '');
  (materials.length ? materials : ['Framework text for the benchmarks listed above', 'Projector and student handouts']).forEach((m) => out.push(`- ${m}`));
  out.push('');

  out.push('## Instructional sequence', '');
  out.push('1. **Bell-ringer / review (5-8 min).** Recall prior benchmark; post the essential question.');
  out.push(`2. **Direct instruction (15-20 min).** ${know.length ? `Content for ${know.map((b) => b.id).join(', ')}.` : 'Frame the task, standards of performance, and safety expectations.'}`);
  out.push('3. **Guided practice (15 min).** Model the procedure, then walk the class through one repetition with checks for understanding.');
  if (perf.length) {
    out.push(`4. **Performance task (25-40 min).** Students demonstrate ${perf.map((b) => b.id).join(', ')}. ${activities[0] || 'Run the procedure to the criteria in the checklist below.'}`);
    activities.slice(1).forEach((a) => out.push(`   - Option: ${a}`));
  } else {
    out.push(`4. **Independent practice (20 min).** ${activities[0] || 'Applied written or analytical task tied to the objectives above.'}`);
  }
  out.push('5. **Closure (5 min).** Exit ticket answering the essential question; preview the next benchmark.', '');

  out.push('## Assessment', '');
  if (know.length) {
    out.push('**Knowledge check** - write items directly from these benchmarks:', '');
    know.forEach((b) => out.push(`- [ ] ${b.id} - ${b.cognitiveLabel}-level item (${b.verbs.join('/') || 'recall'})`));
    out.push('');
  }
  if (perf.length) {
    out.push('**Performance checklist** - observed, pass/retry:', '');
    perf.forEach((b) => {
      out.push(`- [ ] ${b.id} ${b.text}`);
      b.bullets.filter((x) => x.depth === 0).forEach((x) => out.push(`  - [ ] ${x.text}`));
    });
    out.push('');
  }
  out.push('**Recording:** mark each benchmark taught/assessed in the coverage tracker so the course record stays current.', '');

  out.push('## Accommodations and modifications', '');
  out.push('- Provide IEP/504 accommodations as written (extended time, scaffolded notes, read-aloud, checklist prompts).');
  out.push('- ELD support: pre-teach the legal vocabulary above with visuals; allow bilingual glossaries on knowledge checks.');
  if (perf.length) out.push('- Performance tasks: permit alternate positioning, added repetitions, or partner support where the benchmark allows.');
  out.push('');

  out.push('## CTSO and career connection', '');
  out.push(`- ${P.ctso.join(' / ')} tie-in: use this task as practice for a related competitive event or chapter activity.`);
  const socs = [...new Set(coursesUsed.map((c) => `${c.soc} ${c.socTitle}`))];
  out.push(`- Occupational link: ${socs.join('; ')}.`, '');

  if (items.some((b) => b.topics.includes('safety-wellness')) || perf.length) {
    out.push('## Safety', '', '- Review lab/scenario safety rules and PPE before the performance task; stop the activity for any unsafe act.', '');
  }

  out.push('---', `*Generated from the FLDOE Criminal Justice Operations framework (program ${P.programNumber}). Objectives, standards and legal citations are framework text; sequence, materials and assessment prompts are planning scaffolds to adapt.*`);
  return out.join('\n');
}

