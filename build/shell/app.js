/* ---------------------------------------------------------------- router */
function route() {
  const hash = location.hash.replace(/^#\/?/, '');
  const [path, qs] = hash.split('?');
  const parts = path.split('/').filter(Boolean);
  const params = new URLSearchParams(qs || '');

  state.focus = null;
  if (!parts.length) { state.view = 'ask'; render(); return; }

  const [head, arg] = parts;
  if (VIEWS[head]) {
    state.view = head;
    if (head === 'ask' && params.has('q')) { setQuery(params.get('q'), { pushHash: false }); return; }
    render();
    return;
  }
  if (head === 'b' && BY_UID.has(decodeURIComponent(arg || ''))) { focusOn('benchmark', decodeURIComponent(arg)); return; }
  if (head === 'standard' && STD_BY_UID.has(decodeURIComponent(arg || ''))) { focusOn('standard', decodeURIComponent(arg)); return; }
  if (head === 'course' && COURSE_BY_NUM.has(arg)) { focusOn('course', arg); return; }
  state.view = 'ask';
  render();
}

window.addEventListener('hashchange', route);

