function unitMarkdown(unit) {
  const items = unit.uids.map((uid) => BY_UID.get(uid)).filter(Boolean);
  const out = [`## ${unit.name}`, '', `**Length:** ${unit.days || Math.ceil(items.reduce((a, b) => a + b.suggestedPeriods, 0))} days | **Benchmarks:** ${items.length}`, ''];
  const stds = [...new Set(items.map((b) => b._std))];
  stds.forEach((s) => {
    out.push(`**${s.courseTitle} - ${s.id} ${s.text}**`);
    items.filter((b) => b._std === s).forEach((b) => out.push(`- ${b.id} ${b.text}`));
    out.push('');
  });
  const perf = items.filter((b) => b.modality === 'performance');
  if (perf.length) out.push(`*Performance/lab load: ${perf.length} of ${items.length} benchmarks.*`, '');
  return out.join('\n');
}

