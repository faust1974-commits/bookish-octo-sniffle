const QUERY_STOPWORDS = new Set(('the a an of in on for to and or with as is are be do does how what which that this ' +
  'i my me we our you your can should would about when where who why does need any all it its').split(' '));

function tokenize(q) {
  const raw = q.toLowerCase().split(/[^a-z0-9.\-/]+/).filter((t) => t.length > 1);
  const content = raw.filter((t) => !QUERY_STOPWORDS.has(t));
  return content.length ? content : raw;
}

function passesFilters(b) {
  const f = state.filters;
  if (f.course.size && !f.course.has(b.courseNumber)) return false;
  if (f.level.size && !f.level.has(String(b.cognitiveLevel))) return false;
  if (f.modality.size && !f.modality.has(b.modality)) return false;
  if (f.topic.size && !b.topics.some((t) => f.topic.has(t))) return false;
  if (f.flags.has('optional') && !b.optional) return false;
  if (f.flags.has('mock') && !b.mockActivity) return false;
  if (f.flags.has('cited') && b.citationCount === 0) return false;
  if (f.flags.has('repeat') && !b.repeatsIn.length) return false;
  if (f.flags.has('selected') && !state.selection.includes(b.uid)) return false;
  if (f.flags.has('untaught') && state.coverage[b.uid]) return false;
  return true;
}

function search(query) {
  const q = query.trim().toLowerCase();
  const tokens = tokenize(q);
  const pool = BENCH.filter(passesFilters);
  if (!tokens.length) return { tokens, results: pool.map((b) => ({ b, score: 0 })) };

  const scored = [];
  pool.forEach((b) => {
    let score = 0;
    let hits = 0;
    if (b.id.toLowerCase() === q) score += 1000;
    if (b.standardId.toLowerCase() === q) score += 400;
    if (b.courseNumber === q) score += 300;
    if (b._hay.includes(q) && tokens.length > 1) score += 120;
    tokens.forEach((t) => {
      let tokenScore = 0;
      if (b.id.startsWith(t)) tokenScore += 150;
      if (b.standardId.startsWith(t)) tokenScore += 60;
      if (b.text.toLowerCase().includes(t)) tokenScore += 24;
      if (b.bullets.some((x) => x.text.toLowerCase().includes(t))) tokenScore += 12;
      if (b._std.text.toLowerCase().includes(t)) tokenScore += 10;
      if (b._cites.join(' ').toLowerCase().includes(t)) tokenScore += 40;
      if (b.topics.some((tp) => TOPIC_LABEL.get(tp).toLowerCase().includes(t))) tokenScore += 14;
      if (!tokenScore && b._hay.includes(t)) tokenScore += 6;
      if (tokenScore) hits += 1;
      score += tokenScore;
    });
    if (hits === tokens.length) score += 60 * tokens.length;
    if (hits > 0) scored.push({ b, score, hits });
  });

  const all = scored.filter((r) => r.hits === tokens.length);
  const use = all.length ? all : scored;
  use.sort((a, b) => b.score - a.score || a.b.uid.localeCompare(b.b.uid));
  return { tokens, results: use };
}

