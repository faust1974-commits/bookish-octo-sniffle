/* ---------------------------------------------------------------- events */
function setQuery(q, { pushHash = true } = {}) {
  state.query = q;
  $('#q').value = q;
  if (state.view !== 'ask' && q) state.view = 'ask';
  if (pushHash) {
    const target = q ? `#/ask?q=${encodeURIComponent(q)}` : '#/ask';
    if (location.hash !== target) { history.replaceState(null, '', target); }
  }
  render();
}

document.addEventListener('click', (e) => {
  const add = e.target.closest('[data-add]');
  if (add) { toggleSelect(add.dataset.add); return; }

  const cov = e.target.closest('[data-cov]');
  if (cov) {
    const uid = cov.dataset.cov;
    setCoverage(uid, state.coverage[uid] === cov.dataset.v ? '' : cov.dataset.v);
    return;
  }

  const chip = e.target.closest('[data-chip]');
  if (chip) {
    const set = state.filters[chip.dataset.chip];
    const v = chip.dataset.value;
    if (set.has(v)) set.delete(v); else set.add(v);
    render();
    return;
  }

  const act = e.target.closest('[data-action]');
  if (act && ACTIONS[act.dataset.action]) {
    e.preventDefault();
    ACTIONS[act.dataset.action](act.dataset.value);
    return;
  }

  const tab = e.target.closest('[data-view]');
  if (tab) { location.hash = `#/${tab.dataset.view}`; }
});

document.addEventListener('toggle', (e) => {
  const d = e.target;
  if (!(d instanceof HTMLDetailsElement) || !d.id) return;
  if (d.open) state.open.add(d.id); else state.open.delete(d.id);
  persist.open();
}, true);

document.addEventListener('input', (e) => {
  if (e.target.id === 'q') { debouncedSearch(e.target.value); return; }
  const lesson = e.target.closest('[data-lesson]');
  if (lesson) {
    state.lesson[lesson.dataset.lesson] = lesson.value;
    persist.lesson();
    const box = $('#lesson-md');
    if (box) box.value = lessonMarkdown();
    return;
  }
  const unit = e.target.closest('[data-unit]');
  if (unit) {
    const u = state.units.find((x) => x.id === unit.dataset.unit);
    if (u) { u[unit.dataset.field] = unit.value; persist.units(); }
  }
});

const debouncedSearch = debounce((v) => setQuery(v), 130);

document.addEventListener('keydown', (e) => {
  if (e.key === '/' && document.activeElement !== $('#q') && !/input|textarea/i.test(document.activeElement.tagName)) {
    e.preventDefault(); $('#q').focus(); $('#q').select();
  }
  if (e.key === 'Escape') {
    const overlay = $('#export-overlay');
    if (overlay) { overlay.remove(); return; }
    if (document.activeElement === $('#q')) { setQuery(''); $('#q').blur(); }
  }
});

