// Selection and coverage toggles patch only the affected nodes, so Browse keeps
// its open sections and scroll position while the user builds a lesson.
function toggleSelect(uid) {
  const i = state.selection.indexOf(uid);
  if (i >= 0) state.selection.splice(i, 1); else state.selection.push(uid);
  persist.selection();
  if (['lesson', 'plan', 'sequence'].includes(state.view)) { render(); return; }
  const on = state.selection.includes(uid);
  $$(`[data-add="${uid}"]`).forEach((btn) => {
    btn.dataset.on = String(on);
    btn.textContent = on ? '\u2713' : '+';
    btn.title = on ? 'Remove from selection' : 'Add to selection';
  });
  refreshChrome();
}

function setCoverage(uid, value) {
  if (value) state.coverage[uid] = value; else delete state.coverage[uid];
  persist.coverage();
  if (state.view === 'coverage') { render(); return; }
  $$(`[data-cov="${uid}"]`).forEach((btn) => {
    btn.setAttribute('aria-pressed', String(btn.dataset.v === value));
  });
  refreshChrome();
}

// Re-renders the parts of the page that summarise state (tabs, selection panel).
