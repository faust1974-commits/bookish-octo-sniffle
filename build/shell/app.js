function focusOn(type, id) {
  state.focus = { type, id };
  if (type === 'benchmark') {
    const b = BY_UID.get(id);
    state.open.add(domId('c', b.courseNumber));
    state.open.add(domId('s', `${b.courseNumber}:${b.standardId}`));
  } else if (type === 'standard') {
    state.open.add(domId('c', id.split(':')[0]));
    state.open.add(domId('s', id));
  } else {
    state.open.add(domId('c', id));
  }
  persist.open();
  state.view = 'browse';
  render();
  requestAnimationFrame(() => {
    const prefix = type === 'benchmark' ? 'b' : type === 'standard' ? 's' : 'c';
    const el = document.getElementById(domId(prefix, id));
    if (el) {
      el.scrollIntoView({ block: 'center', behavior: 'smooth' });
      el.classList.add('flash');
      setTimeout(() => el.classList.remove('flash'), 2200);
    }
  });
}

