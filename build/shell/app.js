function highlight(text, tokens) {
  let html = esc(text);
  tokens.filter((t) => t.length > 1).forEach((t) => {
    const safe = t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const re = new RegExp(t.length <= 3 ? `\\b(${safe})\\b` : `\\b(${safe})`, 'gi');
    html = html.replace(re, '<mark>$1</mark>');
  });
  return html;
}

