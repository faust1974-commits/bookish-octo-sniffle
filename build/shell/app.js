function renderBrowse() {
  const open = state.focus || {};
  const courses = COURSES.filter((c) => !state.filters.course.size || state.filters.course.has(c.courseNumber));
  const html = courses.map((c) => {
    const stds = c.standards.map((s) => {
      const bs = s.benchmarks.filter(passesFilters);
      if (!bs.length) return '';
      const taught = s.benchmarks.filter((b) => state.coverage[b.uid]).length;
      const rowId = domId('s', s.uid);
      const focused = (open.type === 'standard' && open.id === s.uid)
        || (open.type === 'benchmark' && open.id === `${c.courseNumber}:${s.id.split('.')[0]}.${open.id.split('.')[1]}`)
        || (open.type === 'benchmark' && BY_UID.get(open.id)?.standardId === s.id && open.id.startsWith(`${c.courseNumber}:`));
      const isOpen = focused || state.open.has(rowId) || state.filters.topic.size > 0
        || (state.query.trim().length > 0);
      return `<details class="std" id="${rowId}" ${isOpen ? 'open' : ''}>
        <summary><span class="sid">${esc(s.id)}</span><span style="flex:1">${esc(s.text)}</span>
          <span class="tiny muted" style="white-space:nowrap">${bs.length}/${s.benchmarkCount} &middot; ~${s.suggestedPeriods}p ${taught ? `&middot; ${taught} covered` : ''}</span></summary>
        <div class="body">${bs.map((b) => benchmarkCard(b)).join('')}</div></details>`;
    }).join('');
    if (!stds) return '';
    const rowId = domId('c', c.courseNumber);
    const isOpen = state.open.has(rowId) || open.id === c.courseNumber
      || (open.id || '').startsWith(`${c.courseNumber}:`) || state.filters.course.has(c.courseNumber);
    return `<details class="std course" id="${rowId}" ${isOpen ? 'open' : ''}>
      <summary><span class="sid">${esc(c.courseNumber)}</span>
        <span style="flex:1">${esc(c.title)}${c.altTitle ? `<span class="muted small"> (also: ${esc(c.altTitle)})</span>` : ''}<br>
          <span class="tiny muted">${c.credit} credit &middot; level ${c.level} &middot; SOC ${esc(c.soc)} &middot; standards ${esc(c.standardRange)} &middot; ${c.benchmarkCount} benchmarks${c.optionGroup ? ' &middot; fourth-credit option' : ''}</span></span>
        <button class="iconbtn no-print" data-action="print-course" data-value="${c.courseNumber}">Print</button></summary>
      <div class="body"><p class="small muted">${esc(c.description)}</p>${stds}</div></details>`;
  }).join('');

  return `<div class="grid two"><div>${html || '<div class="empty">No benchmark matches the current filters.</div>'}</div>
    <div class="stack">${filterBar()}${selectionPanel()}</div></div>`;
}

